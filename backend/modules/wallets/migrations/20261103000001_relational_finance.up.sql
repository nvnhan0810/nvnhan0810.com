-- Typed finance tables. IDs are scoped by Identity owner; holidays are shared.
CREATE TABLE finance_profiles (
 user_id UUID PRIMARY KEY REFERENCES identity_users(id) ON DELETE CASCADE,
 next_id BIGINT NOT NULL DEFAULT 0 CHECK (next_id >= 0)
);
CREATE TABLE holidays (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 date DATE NOT NULL UNIQUE,
 name TEXT NOT NULL,
 type TEXT NOT NULL CHECK (type IN ('public','bank','custom')),
 created_at TIMESTAMPTZ,
 updated_at TIMESTAMPTZ
);
CREATE TABLE user_settings (
 user_id UUID NOT NULL REFERENCES finance_profiles(user_id) ON DELETE CASCADE,
 key TEXT NOT NULL,
 value TEXT,
 PRIMARY KEY(user_id,key)
);

CREATE TABLE wallets (
