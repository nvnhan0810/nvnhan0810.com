CREATE OR REPLACE FUNCTION pg_temp.finance_row(row_data JSONB) RETURNS JSONB LANGUAGE plpgsql AS $$
DECLARE k TEXT; v JSONB; result JSONB := row_data;
BEGIN
 FOR k,v IN SELECT * FROM jsonb_each(row_data) LOOP
  IF v = '""'::jsonb OR ((k LIKE '%\_id' ESCAPE '\' OR k='id') AND v IN ('0'::jsonb,'"0"'::jsonb)) THEN
   result := jsonb_set(result,ARRAY[k],'null'::jsonb);
  ELSIF k IN ('paid_at','period_due_date','due_date','started_at','date','effective_from','ends_at','transacted_at','reminded_on') AND v #>> '{}' ~ '^\d{2}/\d{2}/\d{4}$' THEN
   result := jsonb_set(result,ARRAY[k],to_jsonb(to_date(v #>> '{}','DD/MM/YYYY')));
  END IF;
 END LOOP;
 RETURN result;
END $$;

