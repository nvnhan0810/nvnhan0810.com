CREATE TABLE todo_user_states (
 user_id UUID PRIMARY KEY REFERENCES identity_users(id) ON DELETE CASCADE,
 version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE todo_projects (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id UUID NOT NULL REFERENCES identity_users(id) ON DELETE CASCADE,
 name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 255),
 git_repo_url TEXT,
 domain TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 deleted_at TIMESTAMPTZ,
 UNIQUE(user_id,id)
);
CREATE UNIQUE INDEX todo_project_repo_unique ON todo_projects(user_id,git_repo_url) WHERE deleted_at IS NULL AND git_repo_url IS NOT NULL;
CREATE TABLE todos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id UUID NOT NULL REFERENCES identity_users(id) ON DELETE CASCADE,
 project_id BIGINT,
 title TEXT NOT NULL CHECK (length(title) BETWEEN 1 AND 255),
 description TEXT,
 status TEXT NOT NULL DEFAULT 'backlog' CHECK (status IN ('backlog','todo','in_progress','done','rejected')),
 priority TEXT NOT NULL DEFAULT 'medium' CHECK (priority IN ('low','medium','high','urgent')),
 started_at TIMESTAMPTZ,
 due_at TIMESTAMPTZ,
 closed_at TIMESTAMPTZ,
 is_urgent BOOLEAN NOT NULL DEFAULT false,
 is_important BOOLEAN NOT NULL DEFAULT false,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 deleted_at TIMESTAMPTZ,
 UNIQUE(user_id,id),
 FOREIGN KEY(user_id,project_id) REFERENCES todo_projects(user_id,id) ON DELETE SET NULL(project_id)
);
CREATE INDEX todos_owner_status ON todos(user_id,status) WHERE deleted_at IS NULL;
CREATE INDEX todos_owner_project ON todos(user_id,project_id) WHERE deleted_at IS NULL;
CREATE TABLE eisenhower_logs (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 user_id UUID NOT NULL REFERENCES identity_users(id) ON DELETE CASCADE,
 todo_id BIGINT NOT NULL,
 is_urgent BOOLEAN NOT NULL,
 is_important BOOLEAN NOT NULL,
 created_by UUID NOT NULL REFERENCES identity_users(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 FOREIGN KEY(user_id,todo_id) REFERENCES todos(user_id,id) ON DELETE CASCADE
);
CREATE TABLE todo_pomodoro_states (
 user_id UUID PRIMARY KEY REFERENCES identity_users(id) ON DELETE CASCADE,
 focus_minutes INTEGER NOT NULL DEFAULT 20 CHECK (focus_minutes BETWEEN 1 AND 180),
 short_break_minutes INTEGER NOT NULL DEFAULT 5 CHECK (short_break_minutes BETWEEN 1 AND 60),
 sessions_before_long_break INTEGER NOT NULL DEFAULT 4 CHECK (sessions_before_long_break BETWEEN 1 AND 12),
 long_break_minutes INTEGER NOT NULL DEFAULT 15 CHECK (long_break_minutes BETWEEN 1 AND 60),
 phase TEXT NOT NULL DEFAULT 'focus' CHECK (phase IN ('focus','short_break','long_break')),
 remaining_ms BIGINT NOT NULL DEFAULT 1200000 CHECK (remaining_ms>=0),
 ends_at BIGINT,
 focus_count INTEGER NOT NULL DEFAULT 0 CHECK (focus_count>=0),
 active_todo_id BIGINT,
 is_running BOOLEAN NOT NULL DEFAULT false,
 session_uuid UUID,
 last_focused_at TIMESTAMPTZ,
 client_updated_at BIGINT NOT NULL DEFAULT 0,
 FOREIGN KEY(user_id,active_todo_id) REFERENCES todos(user_id,id) ON DELETE SET NULL(active_todo_id),
 CHECK (NOT is_running OR (ends_at IS NOT NULL AND session_uuid IS NOT NULL))
);
CREATE INDEX todo_pomodoro_due ON todo_pomodoro_states(ends_at) WHERE is_running;
CREATE TABLE web_push_subscriptions (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 user_id UUID NOT NULL REFERENCES identity_users(id) ON DELETE CASCADE,
 endpoint TEXT NOT NULL,
 public_key TEXT NOT NULL,
 auth_token TEXT NOT NULL,
 content_encoding TEXT NOT NULL DEFAULT 'aes128gcm' CHECK (content_encoding='aes128gcm'),
 user_agent TEXT,
 last_focused_at TIMESTAMPTZ,
 is_active BOOLEAN NOT NULL DEFAULT true,
 failed_sent INTEGER NOT NULL DEFAULT 0,
 last_failed_reason TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(user_id,endpoint)
);
-- A phase transition and its delivery event commit together, so restarts don't lose notifications.
CREATE TABLE todo_push_events (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 user_id UUID NOT NULL REFERENCES identity_users(id) ON DELETE CASCADE,
 session_uuid UUID NOT NULL UNIQUE,
 from_phase TEXT NOT NULL,
 to_phase TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 available_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 attempts INTEGER NOT NULL DEFAULT 0,
 delivered_at TIMESTAMPTZ
);
CREATE TABLE todo_push_deliveries (
 event_id BIGINT NOT NULL REFERENCES todo_push_events(id) ON DELETE CASCADE,
 subscription_id BIGINT NOT NULL REFERENCES web_push_subscriptions(id) ON DELETE CASCADE,
 delivered_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY(event_id,subscription_id)
);
